#!/usr/bin/env python3
"""Generate the Gazebo worlds used in Stages 2-5. Runs on the HOST:
    python3 scripts/common/gen_world.py

Every world is generated from a fixed random seed, so "the corridor" means the
same corridor on every machine and in every re-run.

  room        textured box room + clutter       Stage 2 baseline, everything should work
  room_plain  same room, all surfaces flat grey  vision starves; LiDAR unaffected
  corridor    80 m straight corridor             LiDAR degenerates along its axis
  field       flat grass field, sparse objects   LiDAR degenerates (a plane); vision fine
  urban       city blocks, 8-45 m buildings      the altitude sweep (Stage 4)
"""
import os
import random

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "sim", "evtol_sim", "worlds")
TEXTURED = ["Gazebo/Bricks", "Gazebo/WoodPallet", "Gazebo/Wood",
            "Gazebo/CeilingTiled", "Gazebo/PaintedWall", "Gazebo/Residential"]


def header(name):
    # Physics at 1000 Hz: the 200 Hz IMU lands on every 5th step exactly.
    # Gravity and magnetic field: PX4's values, placed at <world> level, where
    # SDF 1.6 defines them. (The guide, like PX4's own empty.world, put them inside
    # <physics>; Gazebo 11 rejects them there -- "SetParam(gravity) bad any_cast" --
    # and silently uses the SDF default 9.8: measured 9.8000 m/s^2 at rest.
    # See docs/stage2_log.md.)
    return f"""<?xml version="1.0"?>
<!-- GENERATED by scripts/common/gen_world.py. Do not edit. -->
<sdf version="1.6">
  <world name="{name}">
    <gravity>0 0 -9.8066</gravity>
    <magnetic_field>6.0e-6 2.3e-5 -4.2e-5</magnetic_field>
    <physics name="default_physics" default="0" type="ode">
      <ode>
        <solver><type>quick</type><iters>10</iters><sor>1.3</sor>
          <use_dynamic_moi_rescaling>0</use_dynamic_moi_rescaling></solver>
        <constraints><cfm>0</cfm><erp>0.2</erp>
          <contact_max_correcting_vel>100</contact_max_correcting_vel>
          <contact_surface_layer>0.001</contact_surface_layer></constraints>
      </ode>
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1</real_time_factor>
      <real_time_update_rate>1000</real_time_update_rate>
    </physics>
    <scene><ambient>0.6 0.6 0.6 1</ambient><background>0.7 0.8 1 1</background><shadows>false</shadows></scene>
    <include><uri>model://sun</uri></include>
    <model name="ground">
      <static>true</static>
      <link name="link">
        <collision name="c"><geometry><plane><normal>0 0 1</normal><size>2000 2000</size></plane></geometry></collision>
      </link>
    </model>
"""


FOOTER = "  </world>\n</sdf>\n"


def box(name, x, y, z, sx, sy, sz, mat, yaw=0.0):
    """Static textured box whose BASE sits at height z."""
    return f"""    <model name="{name}">
      <static>true</static>
      <pose>{x:.3f} {y:.3f} {z + sz / 2:.3f} 0 0 {yaw:.3f}</pose>
      <link name="link">
        <collision name="c"><geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry></collision>
        <visual name="v"><geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry>
          <material><script><uri>file://media/materials/scripts/gazebo.material</uri><name>{mat}</name></script></material>
        </visual>
      </link>
    </model>
"""


def room(plain):
    rnd = random.Random(7)
    pick = (lambda: "Gazebo/Grey") if plain else (lambda: rnd.choice(TEXTURED))
    w = header("room_plain" if plain else "room")
    L, W, H, t = 14.0, 10.0, 3.0, 0.2
    w += box("floor", 0, 0, -0.1, L, W, 0.1, "Gazebo/Grey" if plain else "Gazebo/WoodFloor")
    w += box("wall_n", 0, W / 2, 0, L, t, H, pick())
    w += box("wall_s", 0, -W / 2, 0, L, t, H, pick())
    w += box("wall_e", L / 2, 0, 0, t, W, H, pick())
    w += box("wall_w", -L / 2, 0, 0, t, W, H, pick())
    # Clutter gives ORB features and LiDAR structure. Inside the flight
    # envelope (|x|<4, |y|<3) boxes stay below 0.8 m so the rig, which flies
    # at 1.0-2.0 m, never passes through one.
    for i in range(40):
        x, y = rnd.uniform(-6.3, 6.3), rnd.uniform(-4.3, 4.3)
        inside = abs(x) < 4.0 and abs(y) < 3.0
        h = rnd.uniform(0.2, 0.8) if inside else rnd.uniform(0.4, 2.2)
        w += box(f"clutter_{i}", x, y, 0, rnd.uniform(0.3, 1.0), rnd.uniform(0.3, 1.0),
                 h, pick(), rnd.uniform(0, 3.14))
    return w + FOOTER


def corridor():
    rnd = random.Random(11)
    w = header("corridor")
    L, W, H, t = 80.0, 3.0, 3.0, 0.2
    w += box("floor", L / 2 - 5, 0, -0.1, L, W + 2, 0.1, "Gazebo/WoodFloor")
    # Flat, featureless-in-geometry walls: along x, every scan looks the same to
    # a LiDAR. Textured, so vision is NOT starved -- that isolates the effect.
    for side, y in (("l", W / 2), ("r", -W / 2)):
        for k in range(8):
            w += box(f"wall_{side}{k}", k * 10.0, y, 0, 10.0, t, H, rnd.choice(TEXTURED))
    w += box("end_w", -5, 0, 0, t, W, H, "Gazebo/Bricks")
    w += box("end_e", L - 5, 0, 0, t, W, H, "Gazebo/Bricks")
    return w + FOOTER


def field():
    rnd = random.Random(13)
    w = header("field")
    w += box("grass", 0, 0, -0.1, 400, 400, 0.1, "Gazebo/Grass")
    for i in range(12):                                # sparse, far apart
        w += box(f"post_{i}", rnd.uniform(-150, 150), rnd.uniform(-150, 150), 0,
                 1.0, 1.0, rnd.uniform(2, 6), "Gazebo/Wood")
    return w + FOOTER


def urban():
    rnd = random.Random(17)
    w = header("urban")
    w += box("streets", 0, 0, -0.1, 400, 400, 0.1, "Gazebo/Road")
    block, street = 30.0, 14.0
    for i in range(-5, 6):
        for j in range(-5, 6):
            if abs(i) <= 0 and abs(j) <= 0:
                continue                               # open plaza for take-off
            cx, cy = i * (block + street), j * (block + street)
            for k in range(rnd.randint(1, 3)):
                sx, sy = rnd.uniform(8, 25), rnd.uniform(8, 25)
                x = cx + rnd.uniform(-(block - sx) / 2, (block - sx) / 2)
                y = cy + rnd.uniform(-(block - sy) / 2, (block - sy) / 2)
                w += box(f"bldg_{i}_{j}_{k}", x, y, 0, sx, sy, rnd.uniform(8, 45),
                         rnd.choice(TEXTURED))
    return w + FOOTER


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, text in (("room", room(False)), ("room_plain", room(True)),
                       ("corridor", corridor()), ("field", field()), ("urban", urban())):
        with open(os.path.join(OUT, name + ".world"), "w") as f:
            f.write(text)
        print("  wrote sim/evtol_sim/worlds/%s.world" % name)


if __name__ == "__main__":
    main()

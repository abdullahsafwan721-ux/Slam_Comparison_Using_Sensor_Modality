#!/usr/bin/env bash
# Stage 2 verification: the simulated sensor rig recorded AGAIN in Gazebo and proven against
# ground truth, next to the stored Stage 2 recording. HOST, project root, no other simulation:
#   bash scripts/stage2/verify_stage2.sh              # ~15 min
#   GUI=true bash scripts/stage2/verify_stage2.sh     # Gazebo window open during the 120 s recording,
#                                                     # pictures kept in <V>/shots/
#   RTF=0.5 bash scripts/stage2/verify_stage2.sh      # simulation at half real time (scripts/tools/sim_rtf.sh):
#                                                     # when the GPU is busy with other work, Gazebo drops
#                                                     # camera frames at full speed; the data are in sim time
# Writes only V (default output/final_verification/stage2), replaced on every run. Never touches
# output/stage2 (the Stage 2 result and Stage 3's input).
#  1 generators  gen_configs.py + gen_world.py regenerate every tracked generated file identically
#  2 record      a new 120 s scripted room bag (record_scripted.sh, exactly the Stage 2 recording)
#  3 gate        verify_sim_bag.py on it: every check passes
#  4 compare     its gate values, sensor timing and camera/LiDAR extrinsic checks against the
#                stored Stage 2 bag's (sim_bag_diagnostics.py, camera_check.py)
#  5 worlds      all five worlds load and pass the gate (20 s each)
set -o pipefail
[ -f compose.yaml ] || { echo "run from the project root"; exit 1; }
V=${V:-output/final_verification/stage2}
S=output/stage2
C="docker compose run --rm -T"
FAILED=(); T0=$(date +%s)
step() { echo; echo "==[$1] $2   ($(date +%T))"; }
res() { [ "$2" -eq 0 ] || FAILED+=("$1"); }
exec 2> >(grep --line-buffered -v -E "^ Container .* (Creating|Created)" >&2)
echo "Stage 2 verification  $(date -Is)  git $(git rev-parse --short HEAD)  GUI=${GUI:-false}  RTF=${RTF:-1 (real time)}"
nvidia-smi --query-gpu=utilization.gpu,memory.used --format=csv,noheader 2>/dev/null | sed "s/^/  ----  GPU load before the start (utilisation, memory): /"
{ pgrep -x gzserver || pgrep -x rosmaster || pgrep -x gzclient; } >/dev/null && { echo "!! a simulator or ROS master is already running on this host"; exit 1; }
$C eval bash -c "rm -rf /$V" >/dev/null 2>&1; mkdir -p "$V"
gate() { $C sim bash -c "source /scripts/common/sim_env.sh >/dev/null 2>&1 && python3 /scripts/stage2/verify_sim_bag.py /$1"; }

step 1 "generators: every generated file regenerates identically"
rc=0
python3 scripts/common/gen_configs.py > "$V/gen_configs.log" 2>&1 || { echo "  FAIL  gen_configs.py"; rc=1; }
python3 scripts/common/gen_world.py > "$V/gen_world.log" 2>&1 || { echo "  FAIL  gen_world.py"; rc=1; }
if [ -z "$(git status --porcelain -- sim config/generated)" ]; then
  echo "  PASS  sim/evtol_sim + config/generated: $(git ls-files sim config/generated | wc -l) tracked files regenerated byte-identically"
else
  echo "  FAIL  regenerated files differ from the committed ones:"; git status --short -- sim config/generated | sed 's/^/          /'; rc=1
fi
res 1 $rc

step 2 "record a new 120 s scripted room bag in Gazebo"
N=s2verify_$$
$C --name $N sim bash /scripts/stage2/record_scripted.sh room 120 "/$V/scripted_room.bag" "${GUI:-false}" > "$V/record.log" 2>&1 &
RP=$!
RT=; if [ -n "${RTF:-}" ]; then bash scripts/tools/sim_rtf.sh $N "$RTF" > "$V/rtf_room.log" 2>&1 & RT=$!; fi
if [ "${GUI:-false}" = true ]; then       # pictures of the Gazebo window, seen from a corner of the room
  bash scripts/tools/capture_gazebo.sh "$V/shots" $N 10 40 room > "$V/capture.log" 2>&1 &
fi
wait $RP; rc=$?
[ -n "$RT" ] && { kill $RT 2>/dev/null; wait $RT 2>/dev/null; }
[ -s "$V/rtf_room.log" ] && sed "s/^/  ----  /" "$V/rtf_room.log"
if [ $rc -eq 0 ] && [ -s "$V/scripted_room.bag" ]; then
  echo "  PASS  $V/scripted_room.bag  $(du -h "$V/scripted_room.bag" | cut -f1)"
else
  echo "  FAIL  recording (rc $rc), see $V/record.log"; tail -5 "$V/record.log" | sed 's/^/          /'; rc=1
fi
grep -c "\[Err\]" "$V/scripted_room.sim.log" 2>/dev/null | xargs -I{} echo "  ----  Gazebo [Err] lines in the simulator log: {}"
res 2 $rc

step 3 "the Stage 2 gate (verify_sim_bag.py) on the new bag"
rc=0
gate "$V/scripted_room.bag" > "$V/scripted_room.gate.txt" 2>&1
sed 's/^/     /' "$V/scripted_room.gate.txt" | grep -E "PASS|FAIL|ALL|FAILED"
grep -q "ALL CHECKS PASSED" "$V/scripted_room.gate.txt" && echo "  PASS  gate: $(grep -c '^PASS' "$V/scripted_room.gate.txt") of $(grep -cE '^(PASS|FAIL)' "$V/scripted_room.gate.txt") checks" \
  || { echo "  FAIL  the gate did not pass"; rc=1; }
res 3 $rc

step 4 "compare with the stored Stage 2 recording (gate values, timing, extrinsics)"
$C sim bash -c "source /scripts/common/sim_env.sh >/dev/null 2>&1 && \
    python3 /scripts/stage2/sim_bag_diagnostics.py /$V/scripted_room.bag /$V/scripted_room_diag > /$V/scripted_room_diag.txt 2>&1; \
    python3 /scripts/stage2/camera_check.py /$V/scripted_room.bag /sim/worlds/room.world /$V/scripted_room_camcheck > /$V/scripted_room_camcheck.txt 2>&1"
python3 - "$S" "$V" <<'EOF'
import re, sys
S, V = sys.argv[1:3]
fails = 0
def rd(p):
    try: return open(p).read()
    except OSError: return ""
def gate(t):
    out = {}
    for l in t.splitlines():
        m = re.match(r"(PASS|FAIL)\s+(.{44})\s*(.*)", l)
        if m: out[m.group(2).strip()] = (m.group(1), m.group(3).strip())
    return out
a, b = gate(rd(S + "/scripted_room.gate.txt")), gate(rd(V + "/scripted_room.gate.txt"))
print("  %-44s %-38s %s" % ("gate check", "stored Stage 2 bag (5 Nov)", "new bag"))
for k in a:
    print("  %-44s %-38s %s" % (k, a[k][1][:38], b.get(k, ("-", "MISSING"))[1]))
    if b.get(k, ("FAIL",))[0] != "PASS": fails += 1
def num(t, pat):
    m = re.search(pat, t)
    return float(m.group(1)) if m else None
checks = [  # name, file, regex, tolerance (absolute, against the stored value)
    ("LiDAR stamp vs true scan time (ms)", "_diag.txt", r"best delta = ([-+\d.]+) ms", 2.0),
    ("stationary hold in the bag (s)", "_diag.txt", r"-> ([\d.]+) s of hold", 0.5),
    ("|accel| at rest (m/s^2)", "_diag.txt", r"\|accel\| at rest = ([\d.]+)", 0.0005),
    ("camera stamp vs image content (ms)", "_camcheck.txt", r"image stamp shift.*peak at ([-+\d.]+) ms", 3.0),
    ("camera rotation x, best (deg)", "_camcheck.txt", r"rotation about camera x.*peak at ([-+\d.]+)", 0.1),
    ("camera rotation y, best (deg)", "_camcheck.txt", r"rotation about camera y.*peak at ([-+\d.]+)", 0.1),
    ("camera rotation z, best (deg)", "_camcheck.txt", r"rotation about camera z.*peak at ([-+\d.]+)", 0.1),
    ("camera translation x, best (m)", "_camcheck.txt", r"translation along camera x.*peak at ([-+\d.]+)", 0.005),
    ("camera translation y, best (m)", "_camcheck.txt", r"translation along camera y.*peak at ([-+\d.]+)", 0.005),
    ("camera translation z, best (m)", "_camcheck.txt", r"translation along camera z.*peak at ([-+\d.]+)", 0.005),
    ("ORB-SLAM3 vs FAST-LIVO2 extrinsic (max diff)", "_camcheck.txt", r"max \|difference\| ([-+\d.e]+)", 1e-6),
]
print()
print("  %-44s %10s %10s %10s" % ("diagnostic", "stored", "new", "tolerance"))
for name, suf, pat, tol in checks:
    x, y = num(rd(S + "/scripted_room" + suf), pat), num(rd(V + "/scripted_room" + suf), pat)
    ok = x is not None and y is not None and abs(x - y) <= tol
    fails += not ok
    print("  %s %-44s %10s %10s %10s" % ("PASS" if ok else "FAIL", name, x, y, tol))
rates = re.findall(r"^(\S+)\s+n=\s*(\d+).*rate=\s*([\d.]+) Hz.*min=([\d.]+)\s+max=([\d.]+)", rd(V + "/scripted_room_diag.txt"), re.M)
for t, n, r, lo, hi in rates:
    print("  ----  %-28s n=%6s  %6s Hz  dt %s-%s s" % (t, n, r, lo, hi))
print("  %s  new recording agrees with the stored one" % ("PASS" if fails == 0 else "FAIL (%d)" % fails))
sys.exit(1 if fails else 0)
EOF
res 4 $?

step 5 "all five worlds load and pass the gate (20 s each)"
rc=0
for w in room room_plain corridor field urban; do
  mkdir -p "$V/worlds"
  RT=; if [ -n "${RTF:-}" ]; then bash scripts/tools/sim_rtf.sh s2verify_${w}_$$ "$RTF" > "$V/rtf_$w.log" 2>&1 & RT=$!; fi
  $C --name s2verify_${w}_$$ sim bash /scripts/stage2/record_scripted.sh $w 20 "/$V/worlds/$w.bag" > "$V/worlds_$w.log" 2>&1
  [ -n "$RT" ] && { kill $RT 2>/dev/null; wait $RT 2>/dev/null; }
  gate "$V/worlds/$w.bag" > "$V/worlds/$w.gate.txt" 2>&1
  e=$(grep -c "\[Err\]" "$V/worlds/$w.sim.log" 2>/dev/null)
  g=$(grep -oE "\|accel\| at rest == g +[0-9.]+" "$V/worlds/$w.gate.txt" | awk '{print $NF}')
  if grep -q "ALL CHECKS PASSED" "$V/worlds/$w.gate.txt"; then
    echo "  PASS  $w: $(grep -c '^PASS' "$V/worlds/$w.gate.txt") checks passed, |accel| at rest $g m/s^2, Gazebo [Err] lines: ${e:-?}"
  else
    echo "  FAIL  $w: $(grep '^FAIL' "$V/worlds/$w.gate.txt" | head -3 | tr '\n' ' ')"; rc=1
  fi
done
res 5 $rc

$C eval chown -R "$(id -u):$(id -g)" "/$V" >/dev/null 2>&1
if [ "${GUI:-false}" = true ]; then
  for _ in $(seq 60); do grep -q "pictures in" "$V/capture.log" 2>/dev/null && break; sleep 1; done
  echo; echo "  ----  $(ls "$V"/shots/*.png 2>/dev/null | wc -l) pictures of the Gazebo window in $V/shots/"
fi
echo
echo "== Stage 2 verification finished in $(( ($(date +%s) - T0) / 60 )) min"
if [ ${#FAILED[@]} -eq 0 ]; then echo "== ALL STEPS PASSED"; else echo "== FAILED STEPS: ${FAILED[*]}"; fi
exit ${#FAILED[@]}

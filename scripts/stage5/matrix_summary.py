#!/usr/bin/env python3
"""Stage 5 extension: the closed-loop matrix next to Stage 4's open-loop matrix (host, project root):

    python3 scripts/stage5/matrix_summary.py [output/stage5/matrix]

For every method and condition flown by run_closed_loop_matrix.sh:
  * did the mission complete (take-off, profile, landing, disarm)?
  * the SLAM method's APE in the loop, and Stage 4's open-loop APE for the same condition
    (median of 3 replays, output/stage4/<group>/eval/summary_extra.csv): does closing the loop
    change what SLAM delivers?
  * PX4's APE, and PX4 vs truth UNALIGNED in its own frame while airborne: what the vehicle
    believed against where it was -- the number that decides whether it can fly on SLAM;
  * EKF2's lag behind the SLAM pose, the fault outcome, PX4's failsafe mode changes.
Writes <root>/matrix_tables.md and <root>/matrix_scorecard.png.
"""
import json
import os
import sys

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = sys.argv[1] if len(sys.argv) > 1 else "output/stage5/matrix"
S4 = "output/stage4"
ALGOS = {"fastlio2": ("FAST-LIO2", "#2a78d6"), "fastlivo2": ("FAST-LIVO2", "#eb6834")}
CONDS = ["room", "room_plain", "corridor", "field"] + ["urban_alt%d" % h for h in (10, 20, 30, 40, 50, 60)] + \
        ["urban_speed%d" % v for v in (2, 5, 8)] + ["imu_x%d" % s for s in (3, 10, 30)] + \
        ["room_lidar_drop_2s", "room_lidar_drop_5s", "room_cam_black_5s"]
INK, MUT, GRID = "#1f2933", "#6b7280", "#e5e7eb"


def stage4_group(c):
    if c.startswith("urban_alt"):
        return "altitude"
    if c.startswith("urban_speed"):
        return "speed"
    if c.startswith("imu_x"):
        return "imu"
    if c.startswith("room_") and c != "room_plain":
        return "faults"
    return "environments"


def stage4_ape(algo, c):
    """Stage 4's open-loop flight APE (median of 3 replays), m; imu_x1 is urban_speed5."""
    import csv
    g = stage4_group(c)
    p = os.path.join(S4, g, "eval", "summary_extra.csv")
    if not os.path.exists(p):
        return None
    for r in csv.DictReader(open(p)):
        if r["condition"] == c and r["algorithm"] == algo:
            try:
                return float(r["ape_air_rmse"])
            except ValueError:
                return None
    return None


def load(algo, c):
    F = os.path.join(ROOT, algo, "flights")
    j = os.path.join(F, c + ".closed_loop.json")
    if not os.path.exists(j):
        return None
    o = json.load(open(j))
    ml = os.path.join(F, c + ".mission.log")
    o["_complete"] = os.path.exists(ml) and "landed and disarmed" in open(ml).read()
    for k in (algo, "px4"):
        p = os.path.join(ROOT, algo, "eval", "%s__%s__r1_extra.json" % (k, c))
        o["_ape_" + ("slam" if k == algo else "px4")] = json.load(open(p)).get("ape_air_rmse") if os.path.exists(p) else None
    return o


def cm(v, nd=1):
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return "-"
    v *= 100
    if v >= 1000:                         # metres beyond 10 m: a divergence, not a centimetre error
        return "%.0f m" % (v / 100)
    return ("%.0f" % v) if v >= 100 else ("%.*f" % (nd, v))


def note(o):
    out = []
    fl = o.get("fault")
    if fl:
        out.append("pose gap %.1f s, PX4 max %s cm in fault + 10 s" % (
            fl["vision_gap_s"], cm(fl["px4_truth_fault_plus10s"]["max_m"]) if fl.get("px4_truth_fault_plus10s") else "-"))
    odd = [m for m in o.get("modes", []) if m[1] not in ("OFFBOARD", "AUTO.LAND", "AUTO.LOITER", "MANUAL") and m[0] > 0]
    if odd:
        out.append("PX4 modes: " + ", ".join("%+.0f s %s" % (m[0], m[1]) for m in odd))
    return "; ".join(out)


def main():
    L = ["# Stage 5 extension: the closed loop over the Stage 4 matrix", "",
         "Generated by scripts/stage5/matrix_summary.py. PX4 flies on the SLAM method ALONE (no GPS, barometer, "
         "magnetometer). APE in cm over the flight window (SE(3)-aligned); 'open loop' = Stage 4's replay of a flight "
         "flown on ground truth (median of 3). 'PX4 vs truth' is UNALIGNED, in PX4's own frame, take-off to first "
         "touchdown: what the vehicle believed against where it was.", ""]
    data = {}
    for a, (lab, _) in ALGOS.items():
        evd = os.path.join(ROOT, a, "ev_delay.txt")
        L += ["## %s%s" % (lab, "  (EKF2_EV_DELAY %s ms; %s)" % tuple(open(evd).read().strip().split("\n", 1)) if os.path.exists(evd) else ""), "",
              "| Condition | Mission | SLAM APE, closed loop | SLAM APE, open loop (Stage 4) | PX4 APE | PX4 vs truth (max) | EKF2 lag (s) | Notes |",
              "|---|---|---|---|---|---|---|---|"]
        for c in CONDS:
            if a == "fastlio2" and c.startswith("room_cam"):
                continue
            o = load(a, c)
            s4 = stage4_ape(a, c if c != "imu_x1" else "urban_speed5")
            if o is None:
                L.append("| %s | not flown | - | %s | - | - | - | |" % (c, cm(s4, 2)))
                continue
            data[(a, c)] = (o, s4)
            pt = o.get("px4_truth")
            L.append("| %s | %s | %s | %s | %s | %s (%s) | %s | %s |" % (
                c, "complete" if o["_complete"] else "**INCOMPLETE**", cm(o["_ape_slam"], 2), cm(s4, 2), cm(o["_ape_px4"], 2),
                cm(pt["rmse_m"]) if pt else "-", cm(pt["max_m"]) if pt else "-", o.get("ekf_lag_s"), note(o)))
        L.append("")
    open(os.path.join(ROOT, "matrix_tables.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))
    # scorecard: PX4 vs truth (what the vehicle believed vs where it was), per condition and method
    conds = [c for c in CONDS if any((a, c) in data for a in ALGOS)]
    if not conds:
        return
    fig, ax = plt.subplots(figsize=(10, 0.36 * len(conds) + 1.6))
    y = np.arange(len(conds))
    for k, (a, (lab, col)) in enumerate(ALGOS.items()):
        for i, c in enumerate(conds):
            if (a, c) not in data:
                continue
            o, s4 = data[(a, c)]
            v = o["px4_truth"]["rmse_m"] * 100 if o.get("px4_truth") else np.nan
            yy = i + (k - 0.5) * 0.36
            ax.barh(yy, v, height=0.32, color=col if o["_complete"] else "none", edgecolor=col, lw=1.2)
            if s4:
                ax.plot(s4 * 100, yy, "|", color=INK, ms=9, mew=1.5)
    ax.set_xscale("log"); ax.set_yticks(y); ax.set_yticklabels(conds, fontsize=8); ax.invert_yaxis()
    ax.set_xlabel("PX4 estimate vs truth in flight, unaligned (cm, log scale)", color=MUT, fontsize=9)
    ax.grid(True, axis="x", color=GRID, lw=0.6); ax.set_axisbelow(True)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    from matplotlib.lines import Line2D
    from matplotlib.patches import Patch
    hs = [Patch(facecolor=col, edgecolor=col, label="%s: PX4 vs truth, closed loop" % lab) for lab, col in ALGOS.values()]
    hs += [Patch(facecolor="none", edgecolor=MUT, label="hollow: mission incomplete"),
           Line2D([], [], ls="none", marker="|", color=INK, ms=9, mew=1.5, label="SLAM APE, open loop (Stage 4)")]
    ax.legend(handles=hs, fontsize=8, frameon=False, loc="lower right")
    ax.set_title("Closed loop over the Stage 4 matrix: PX4 flying on SLAM alone", fontsize=11, color=INK, loc="left")
    fig.tight_layout()
    fig.savefig(os.path.join(ROOT, "matrix_scorecard.png"), dpi=170)


if __name__ == "__main__":
    main()
